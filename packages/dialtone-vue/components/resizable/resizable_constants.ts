// ─── Defaults ─────────────────────────────────────────────────────────────

/** Default panel size when no initialSize is specified (50% of container). */
export const DEFAULT_PANEL_SIZE = '50p';

/** Minimum panel size in pixels below which a resize is rejected. */
export const MIN_PANEL_SIZE_PX = 10;

// ─── Storage Adapter ───────────────────────────────────────────────────────

/**
 * Interface for pluggable storage backends.
 * Implement this to persist panel layouts to Pinia, Vuex, IndexedDB, etc.
 * The built-in `localStorageAdapter(key)` factory creates a localStorage-backed adapter.
 */
export interface ResizableStorageAdapter {
  /** Persist the current panel layout. */
  save(data: ResizableStoragePanelData[]): void;
  /** Load a previously saved layout. Returns null if nothing is stored. */
  load(): ResizableStoragePanelData[] | null;
  /** Remove all persisted data for this layout. */
  clear(): void;
}

/**
 * Shape of a single panel's persisted data.
 * Intentionally minimal — only what's needed to restore a layout.
 */
export interface ResizableStoragePanelData {
  id: string;
  pixelSize: number;
  collapsed?: boolean;
  autoCollapsed?: boolean;
  manualTargetRatio?: number;
}

// ─── Injection Context ──────────────────────────────────────────────────────
// Single context object for provide/inject between ResizableGroup, Panel, Handle.

export interface ResizableContext {
  // Reactive state
  layout: ComputedRef<LayoutResult>;
  panels: ComputedRef<ResizablePanelState[]>;
  panelMap: ComputedRef<Map<string, ResizablePanelState>>;
  direction: ComputedRef<ResizableDirection>;
  containerSize: ComputedRef<number>;
  containerElement: ComputedRef<HTMLElement | null>;
  isResizing: ComputedRef<boolean>;
  activeHandleId: ComputedRef<string | undefined>;
  isInitializing: ComputedRef<boolean>;
  messages: Record<string, string>;

  // Offset (from fixed header/toolbar)
  offsetHandleStyles: ComputedRef<Record<string, string>>;
  offsetContentStyles: ComputedRef<Record<string, string>>;

  // Operations
  startResize: (handleId: string) => void;
  resetPanels: (
    beforePanelId?: string,
    afterPanelId?: string,
    behavior?: 'both' | 'before' | 'after' | 'all',
  ) => void;
  registerHandle: (instance: ComponentInternalInstance | null) => void;
  unregisterHandle: (instance: ComponentInternalInstance | null) => void;
  registerPanel: (config: ResizablePanelConfig) => void;
  unregisterPanel: (id: string) => void;
  saveToStorage: () => void;
  announce: (message: string) => void;
  collapsePanel: (panelId: string, collapsed: boolean) => void;
  emitPanelResize: (panelId: string, size: number) => void;
  commitPanelSize: (panelId: string, pixels: number) => void;
  updateSavedPanel: (panelId: string, updates: Partial<ResizableStoragePanelData>) => void;
}

export const RESIZABLE_CONTEXT_KEY: InjectionKey<ResizableContext> = Symbol('resizable-context');

/**
 * Build a composite handle ID from the before and after panel IDs.
 * Handles use the format "{beforePanelId}:{afterPanelId}" throughout the system.
 */
export function buildHandleId(beforeId: string, afterId: string): string {
  return `${beforeId}:${afterId}`;
}
