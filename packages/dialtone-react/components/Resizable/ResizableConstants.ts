/**
 * Resizable panel system — types and the context.
 *
 * @see Resizable.tsx — provides the context
 * @see ResizablePanel.tsx — consumes panel/layout values
 * @see ResizableHandle.tsx — consumes handle/resize values
 */
import { createContext, useContext } from 'react';
import type { LayoutResult } from './Composables/ComputeLayout';

// ─── Sizing Types ──────────────────────────────────────────────────────────

/**
 * Resizable panels accept Dialtone layout tokens (numeric strings mapped to
 * `--dt-layout-*` pixel values, e.g. '500' → 320px) or percentage values with
 * a 'p' suffix (e.g. '50p' → 50% of the container).
 *
 * The accepted set matches DtBox's layout value surface so the same numeric
 * label resolves to the same pixel size across DtResizable, DtBox, and the
 * `d-w-*` / `d-h-*` utility classes.
 *
 * parseSizeToPixels() warns for unrecognized values.
 */
export type ResizableSizeValue = string;

// ─── Types ──────────────────────────────────────────────────────────────────

export type ResizableDirection = 'row' | 'column';

export interface ResizablePanelConfig {
  /** Panel identifier. Auto-generated by ResizableGroup if not provided. */
  id: string;
  /** Initial size - layout token (e.g., '500') or percentage with 'p' suffix (e.g., '50p') */
  initialSize?: ResizableSizeValue;

  // ─── User Drag Limits (Absolute Boundaries) ───
  /** Hard floor for user dragging. User cannot drag panel smaller than this. */
  userMinSize?: ResizableSizeValue;
  /** Hard ceiling for user dragging. User cannot drag panel larger than this. */
  userMaxSize?: ResizableSizeValue;

  // ─── System Scaling Limits (Operating Range) ───
  /**
   * System scaling floor. System won't compress panel below this during viewport resize.
   * Must be >= userMinSize. Falls back to userMinSize if not specified.
   */
  systemMinSize?: ResizableSizeValue;
  /**
   * System scaling ceiling. System won't expand panel above this during viewport resize.
   * Must be <= userMaxSize. Falls back to userMaxSize if not specified.
   */
  systemMaxSize?: ResizableSizeValue;

  // ─── Auto-Collapse ───
  /**
   * Container width threshold for auto-collapse.
   * When container width drops below this value, panel auto-collapses.
   * This is the container width, not the panel width.
   */
  collapseSize?: ResizableSizeValue;

  // ─── Behavior Flags ───
  /** Whether this panel can be resized by user dragging */
  resizable?: boolean;
  /** Whether this panel can be manually collapsed via UI */
  collapsible?: boolean;
  /** Initial collapsed state */
  collapsed?: boolean;
}

export interface ResizablePanelState extends ResizablePanelConfig {
  // ─── Core State ───
  /** Current size in pixels (primary storage) */
  pixelSize: number;

  // ─── User Drag Constraints (Computed Pixels) ───
  /** Computed pixel value for userMinSize (absolute floor for user dragging) */
  userMinSizePixels?: number;
  /** Computed pixel value for userMaxSize (absolute ceiling for user dragging) */
  userMaxSizePixels?: number;

  // ─── System Scaling Constraints (Computed Pixels) ───
  /** Computed pixel value for systemMinSize (system scaling floor) */
  systemMinSizePixels?: number;
  /** Computed pixel value for systemMaxSize (system scaling ceiling) */
  systemMaxSizePixels?: number;

  // ─── Auto-Collapse State ───
  /** Computed pixel value for collapseSize (container width threshold) */
  collapseSizePixels?: number;
  /** True if panel was auto-collapsed (vs manually collapsed via UI) */
  autoCollapsed?: boolean;

  // ─── Manual Resize Tracking ───
  /**
   * Internal: Stores the user's preferred pixel size when they drag a panel.
   * Used by the drag system to track intent before converting to ratio.
   * Not exposed as a component prop.
   */
  manualTargetSize?: number;
  /**
   * Stores the user's preferred ratio (0–1) when they drag a panel.
   * - undefined: no manual target, panel scales proportionally with viewport
   * - number: panel targets (ratio × containerSize) pixels on each render,
   *   still subject to min/max constraints.
   *
   * Enables correct proportional scaling when the viewport changes.
   * Panel feels "sticky" at the chosen proportion.
   */
  manualTargetRatio?: number;

  // ─── Storage Restoration ───
  /**
   * True if this panel's state was loaded from localStorage on the current
   * initialization pass. Prevents double-restoration when loadFromStorage is
   * called multiple times.
   */
  restoredFromStorage?: boolean;
}

export interface ResizableHandleConfig {
  id: string;
  beforePanelId: string;
  afterPanelId: string;
  direction: ResizableDirection;
}

export type ResizableSizeMode = 'percentage' | 'pixels';

export interface ResizableGroupConfig {
  direction: ResizableDirection;
  panels: ResizablePanelConfig[];
  storageKey?: string; // Optional localStorage key for persistence
  sizeMode?: ResizableSizeMode; // Whether to use percentage or pixel-based sizing
  limitToParent?: boolean; // Limit resizing to parent viewport bounds
}

export interface ResizableGroupState {
  direction: ResizableDirection;
  panels: ResizablePanelState[];
  containerSize: number; // Total container size in pixels
  isResizing: boolean;
  activeHandleId?: string;
}

/** DtResizable's callbacks, as Vue's events: `panel-resize` is `onPanelResize`, and so on. */
export interface ResizableEvents {
  onPanelResize: (panelId: string, size: number) => void;
  onPanelCollapse: (panelId: string, collapsed: boolean) => void;
  onResizeStart: (handleId: string) => void;
  onResizeEnd: (handleId: string) => void;
}

/**
 * Defines collapse behavior for a panel during space constraints.
 * Used to determine which panels collapse first when viewport shrinks.
 */
export interface CollapseRule {
  /** Panel ID this rule applies to */
  panelId: string;
  /** Collapse priority - lower numbers collapse first */
  priority: number;
  /** Optional threshold that triggers collapse (overrides panel's userMinSize) */
  minSizeBeforeCollapse?: ResizableSizeValue;
}

// ─── Defaults ─────────────────────────────────────────────────────────────

/** Default panel size when no initialSize is specified (50% of container). */
export const DEFAULT_PANEL_SIZE = '50p';

/** Minimum panel size in pixels below which a resize is rejected. */
export const MIN_PANEL_SIZE_PX = 10;

/** Centers the 4px handle over the panel boundary. */
export const RESIZABLE_HANDLE_CENTER_OFFSET_PX = 2;

// ─── Storage Adapter ───────────────────────────────────────────────────────

/**
 * Interface for pluggable storage backends.
 * Implement this to persist panel layouts to a store, IndexedDB, etc.
 * The built-in `localStorageAdapter(key)` factory creates a localStorage-backed adapter.
 */
export interface ResizableStorageAdapter {
  /** Persist the current panel layout. */
  save(data: ResizableStoragePanelData[]): void;
  /** Load a previously saved layout. Returns null if nothing is stored. */
  load(): ResizableStoragePanelData[] | null;
  /** Remove all persisted data for this layout. */
  clear(): void;
}

/**
 * Shape of a single panel's persisted data.
 * Intentionally minimal — only what's needed to restore a layout.
 */
export interface ResizableStoragePanelData {
  id: string;
  pixelSize: number;
  collapsed?: boolean;
  autoCollapsed?: boolean;
  manualTargetRatio?: number;
}

// ─── Context ────────────────────────────────────────────────────────────────
// Single context object shared by DtResizable, DtResizablePanel and DtResizableHandle (Vue's provide/inject).

export type ResizableResetBehavior = 'both' | 'before' | 'after' | 'all';

export interface ResizableContext {
  // State, as of the provider's last render
  layout: LayoutResult;
  panels: ResizablePanelState[];
  panelMap: Map<string, ResizablePanelState>;
  direction: ResizableDirection;
  containerSize: number;
  containerElement: HTMLElement | null;
  isResizing: boolean;
  activeHandleId: string | undefined;
  isInitializing: boolean;
  messages: Record<string, string>;

  // Offset (from fixed header/toolbar)
  offsetHandleStyles: Record<string, string>;
  offsetContentStyles: Record<string, string>;

  // Operations
  startResize: (handleId: string) => void;
  resetPanels: (beforePanelId?: string, afterPanelId?: string, behavior?: ResizableResetBehavior) => void;
  registerHandle: (instance: unknown) => void;
  unregisterHandle: (instance: unknown) => void;
  registerPanel: (config: ResizablePanelConfig) => void;
  unregisterPanel: (id: string) => void;
  saveToStorage: () => void;
  announce: (message: string) => void;
  collapsePanel: (panelId: string, collapsed: boolean) => void;
  emitPanelResize: (panelId: string, size: number) => void;
  commitPanelSize: (panelId: string, pixels: number) => void;
  updateSavedPanel: (panelId: string, updates: Partial<ResizableStoragePanelData>) => void;
}

/** Vue's injection key: the context DtResizable provides to its panels and handles, `null` outside one. */
export const RESIZABLE_CONTEXT_KEY = createContext<ResizableContext | null>(null);

/** Vue's `inject(RESIZABLE_CONTEXT_KEY, null)`. */
export function useResizableContext (): ResizableContext | null {
  return useContext(RESIZABLE_CONTEXT_KEY);
}

/**
 * Build a composite handle ID from the before and after panel IDs.
 * Handles use the format "{beforePanelId}:{afterPanelId}" throughout the system.
 */
export function buildHandleId (beforeId: string, afterId: string): string {
  return `${beforeId}:${afterId}`;
}
