#!/usr/bin/env node
// React icons from @dialpad/dialtone-icons' optimized SVGs (dist/svg/icons, from its pre-build), with the same
// names and markup as the Vue icons. Writes icons/generated/index.ts, which is gitignored.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const iconsPkg = fs.realpathSync(path.join(here, '../node_modules/@dialpad/dialtone-icons'));
const svgDir = path.join(iconsPkg, 'dist/svg/icons');
if (!fs.existsSync(svgDir)) {
  console.error(`build-icons: ${svgDir} is missing; build dialtone-icons first (pnpm nx run dialtone-icons:build)`);
  process.exit(1);
}

const lines = [
  '// Generated by scripts/build-icons.mjs from @dialpad/dialtone-icons. Don\'t edit.',
  'import { createIcon } from \'../createIcon\';',
  '',
];
for (const file of fs.readdirSync(svgDir).filter(f => f.endsWith('.svg')).sort()) {
  const svg = fs.readFileSync(path.join(svgDir, file), 'utf8').trim();
  const match = svg.match(/^<svg([^>]*)>([\s\S]*)<\/svg>$/);
  if (!match) throw new Error(`build-icons: can't parse ${file}`);
  const attrs = Object.fromEntries([...match[1].matchAll(/([\w:-]+)="([^"]*)"/g)].map(([, k, v]) => [k, v]));
  const inner = match[2];
  // The same ids the Vue icons scope per instance (transformSVGtoVue.cjs).
  const scoped = /(clip-path|fill)="url\(#/.test(inner) || /(clipPath|linearGradient|radialGradient) id="/.test(inner);
  const name = `dt-icon-${file.replace('.svg', '')}`.toLowerCase().split('-').map(w => w.charAt(0).toUpperCase() + w.slice(1)).join('');
  lines.push(`export const ${name} = /* @__PURE__ */ createIcon(${JSON.stringify(name)}, ${JSON.stringify(attrs)}, ${JSON.stringify(inner)}, ${scoped});`);
}
const outDir = path.join(here, '../icons/generated');
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, 'index.ts'), `${lines.join('\n')}\n`);
