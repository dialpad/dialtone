#!/usr/bin/env node
// Writes the package barrel, index.ts (gitignored), so unit PRs never edit it: every component's
// components/<Name>/index.ts, every common/<dir>/index.ts (mixin hooks, as dialtone-vue exports its mixins), and
// the common modules dialtone-vue exports too. Icons have their own entry point (`@dialpad/dialtone-react/icons`),
// as they're a separate package for Vue. A name exported twice fails typecheck (TS2308), naming both modules.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const pkg = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const COMMON = ['common/constants', 'common/utils', 'common/slots'];

const indexDirs = dir => (fs.existsSync(path.join(pkg, dir))
  ? fs.readdirSync(path.join(pkg, dir), { withFileTypes: true })
    .filter(d => d.isDirectory() && fs.existsSync(path.join(pkg, dir, d.name, 'index.ts')))
    .map(d => `${dir}/${d.name}`)
    .sort()
  : []);

const line = module => `export * from './${module}';`;
const source = [
  '// Generated by scripts/build-index.mjs. Don\'t edit: build, typecheck, test and gate rebuild it.',
  '',
  '// Common',
  ...COMMON.map(line),
  ...indexDirs('common').map(line),
  '',
  '// Components',
  ...indexDirs('components').map(line),
  '',
].join('\n');

const out = path.join(pkg, 'index.ts');
// Unchanged content isn't rewritten, so watchers (Storybook, Vitest) don't see a change.
if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== source) fs.writeFileSync(out, source);
