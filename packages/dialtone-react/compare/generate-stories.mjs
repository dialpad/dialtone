#!/usr/bin/env node
// Writes the comparison Storybook's stories from the running Vue Storybook's
// index: one file per Vue CSF file, one story per Vue story, with the same
// title and export name, so the sidebar and every story id match Vue's. Each
// story renders <CompareFrame>, which shows Vue and React side by side.
//
// Waits for Vue's index.json first (the Vue Storybook can take minutes to come
// up cold). Usage: node compare/generate-stories.mjs [--timeout <seconds>]
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { storyNameFromExport, toId } from 'storybook/internal/csf';

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, 'generated');
const ports = JSON.parse(await readFile(join(here, 'ports.json'), 'utf8'));
const indexUrl = `http://localhost:${ports.vue}/index.json`;
const reactIndexUrl = `http://localhost:${ports.react}/index.json`;

const timeoutArg = process.argv.indexOf('--timeout');
const timeoutSeconds = timeoutArg === -1 ? 600 : Number(process.argv[timeoutArg + 1]);

async function fetchVueIndex () {
  const deadline = Date.now() + timeoutSeconds * 1000;
  let announced = false;
  for (;;) {
    try {
      const response = await fetch(indexUrl);
      if (response.ok) return await response.json();
    } catch {
      // Not listening yet.
    }
    if (Date.now() > deadline) {
      throw new Error(`Vue's story index wasn't reachable at ${indexUrl} within ${timeoutSeconds}s. Start Vue's Storybook with \`pnpm nx run dialtone-vue:start\`.`);
    }
    if (!announced) {
      console.log(`compare: waiting for Vue's story index at ${indexUrl}…`);
      announced = true;
    }
    await new Promise(resolve => setTimeout(resolve, 2000));
  }
}

// React's index, if its Storybook answers within a few seconds (storybook:all
// starts it alongside Vue's, which takes far longer); null otherwise.
async function fetchReactIndex (seconds = 10) {
  const deadline = Date.now() + seconds * 1000;
  for (;;) {
    try {
      const response = await fetch(reactIndexUrl);
      if (response.ok) return await response.json();
    } catch {
      // Not listening (yet).
    }
    if (Date.now() > deadline) return null;
    await new Promise(resolve => setTimeout(resolve, 1000));
  }
}

const fileNameFor = importPath => importPath
  .replace(/^\.\//, '')
  .replace(/\.stories\.[cm]?[jt]sx?$/, '')
  .replace(/[^a-zA-Z0-9]+/g, '_') + '.stories.tsx';

const index = await fetchVueIndex();
const stories = Object.values(index.entries).filter(entry => entry.type === 'story');

// Group by CSF file, keeping Vue's order (export order within each file).
const files = new Map();
for (const entry of stories) {
  if (!files.has(entry.importPath)) files.set(entry.importPath, []);
  files.get(entry.importPath).push(entry);
}

const mismatches = [];
const sources = [];
for (const [importPath, entries] of files) {
  const { title } = entries[0];
  // The id's component part, which a CSF meta.id can override in Vue, so carry
  // it over rather than deriving it from the title.
  const componentId = entries[0].id.split('--')[0];
  const lines = [
    `// Generated by compare/generate-stories.mjs from Vue's ${importPath}. Do not edit.`,
    `import type { Meta, StoryObj } from '@storybook/react-vite';`,
    `import { CompareFrame } from '../CompareFrame';`,
    '',
    `const vueImportPath = ${JSON.stringify(importPath)};`,
    '',
    'const meta: Meta = {',
    `  title: ${JSON.stringify(title)},`,
    `  id: ${JSON.stringify(componentId)},`,
    '  render: (_args, { id, title, globals }) => (',
    '    <CompareFrame storyId={id} title={title} vueImportPath={vueImportPath} globals={globals} />',
    '  ),',
    '};',
    'export default meta;',
    '',
  ];
  for (const entry of entries) {
    if (!entry.exportName) {
      mismatches.push(`${entry.id}: Vue's index has no exportName`);
      continue;
    }
    // The export name goes into the generated source as is, so it must be a
    // plain identifier. The id check below can't vouch for that: the index
    // gives both, and an id can be derived from the same bad name.
    if (!/^[A-Za-z_$][\w$]*$/.test(entry.exportName)) {
      mismatches.push(`${entry.id}: export name ${JSON.stringify(entry.exportName)} isn't a plain identifier`);
      continue;
    }
    const id = toId(componentId, storyNameFromExport(entry.exportName));
    if (id !== entry.id) {
      mismatches.push(`${entry.id}: export ${entry.exportName} would give ${id}`);
      continue;
    }
    // Index entries carry resolved tags: Storybook has already applied a story's
    // `!dev`, removing `dev`. In dev, the sidebar shows only stories tagged
    // `dev`, so a Vue story without it is hidden there; keep it hidden here.
    const tags = (entry.tags ?? []).includes('dev') ? [] : ['!dev'];
    const fields = [`name: ${JSON.stringify(entry.name)}`];
    if (tags.length) fields.push(`tags: ${JSON.stringify(tags)}`);
    lines.push(`export const ${entry.exportName}: StoryObj = { ${fields.join(', ')} };`);
  }
  sources.push([fileNameFor(importPath), lines.join('\n') + '\n']);
}

await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });
await Promise.all(sources.map(([name, source]) => writeFile(join(outDir, name), source)));

console.log(`compare: wrote ${stories.length - mismatches.length} stories in ${sources.length} files to ${outDir}`);
if (mismatches.length) {
  console.error(`compare: skipped ${mismatches.length} stories it can't reproduce:\n  ${mismatches.join('\n  ')}`);
}

// React stories Vue doesn't have: most likely a ported story with the wrong
// title or export name, which the comparison would show as "Not ported yet".
const reactIndex = await fetchReactIndex();
if (!reactIndex) {
  console.log(`compare: React's story index didn't answer at ${reactIndexUrl}; skipped the check for React-only story ids.`);
} else {
  const vueIds = new Set(stories.map(entry => entry.id));
  const reactOnly = Object.values(reactIndex.entries ?? {})
    .filter(entry => entry.type === 'story' && !vueIds.has(entry.id))
    .map(entry => `${entry.id} (${entry.importPath})`);
  if (reactOnly.length) {
    console.warn(`compare: ${reactOnly.length} React stories have no Vue story with the same id (wrong title or export name?):\n  ${reactOnly.join('\n  ')}`);
  }
}
