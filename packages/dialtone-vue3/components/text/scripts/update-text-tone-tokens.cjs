#!/usr/bin/env node
const fs = require('fs');
const path = require('path');

const DOCS_PATH = path.resolve(__dirname, '../../../../dialtone-css/lib/dist/dialtone-docs.json');
const OUTPUT_JSON_PATH = path.resolve(__dirname, '../text_tone_tokens.json');
const OUTPUT_JS_PATH = path.resolve(__dirname, '../text_tone_tokens.js');

const EXCLUDE_REGEX = /\d/;
const EXCLUDED_TOKENS = new Set([
  'neutral-transparent',
]);

function loadDocs () {
  if (!fs.existsSync(DOCS_PATH)) {
    throw new Error(`Dialtone docs file not found at ${DOCS_PATH}`);
  }

  const raw = fs.readFileSync(DOCS_PATH, 'utf8');
  return JSON.parse(raw);
}

function extractToneTokens (docs) {
  const tokens = new Set();

  Object.keys(docs)
    .filter((utility) => utility.startsWith('d-fc-'))
    .forEach((utility) => {
      const token = utility.replace('d-fc-', '');
      if (!EXCLUDE_REGEX.test(token) && !EXCLUDED_TOKENS.has(token)) {
        tokens.add(token);
      }
    });

  return Array.from(tokens).sort();
}

function writeOutputs (tokens) {
  const jsonContent = `${JSON.stringify(tokens, null, 2)}\n`;
  fs.writeFileSync(OUTPUT_JSON_PATH, jsonContent, 'utf8');

  const jsItems = tokens.map((token) => `  '${token}',`).join('\n');
  const jsContent = `// This file is auto-generated by scripts/update-text-tone-tokens.cjs\n// Do not edit this file directly.\n\nexport default [\n${jsItems}\n];\n`;
  fs.writeFileSync(OUTPUT_JS_PATH, jsContent, 'utf8');
}

function main () {
  const docs = loadDocs();
  const tokens = extractToneTokens(docs);
  writeOutputs(tokens);
  console.log(`Generated ${tokens.length} text tone tokens.`);
}

main();
